        # 更新処理(移動)用
        #--------------------------------------------------------------------
        #□ 移動速度
        self.移動速度       = 1.5

        #--------------------------------------------------------------------
        # 更新処理(発射)用
        #--------------------------------------------------------------------
        #□ 発射間隔         ： 発射の間隔時間(単位:fps)
