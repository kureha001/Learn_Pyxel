        #□ シールド総量     ： シールドを蓄えられる最大量
        #□ 威力_弾          ： 弾での攻撃で相手見与えるダメージ量
        #□ 威力_体当たり    ： 体当たりで相手見与えるダメージ量
        self.衝突範囲       = ( 1,1, 6,6 )
        self.シールド総量   = pyxel.width
        self.威力_弾        = 2
        self.威力_体当たり  = 3

